import { contrast } from "./contrast";
import { color, THEMES, type ColorToken, type duration, type easing, type radius, type Theme } from "./tokens";

export type BrandColor = ColorToken | "chart-1" | "chart-2" | "chart-3" | "chart-4" | "chart-5";
export type BrandVar =
  | "font-sans"
  | "font-sans-ar"
  | "font-mono"
  | `radius-${keyof typeof radius}`
  | `duration-${keyof typeof duration}`
  | `ease-${keyof typeof easing}`
  | "slash-run"
  | "gutter";
/** A project's brand: each color one time per mode; `vars` = other `--p-*` names without the prefix. */
export type Brand = {
  dark?: Partial<Record<BrandColor, string>>;
  light?: Partial<Record<BrandColor, string>>;
  vars?: Partial<Record<BrandVar, string>>;
};

/** `--p-name: value;` lines; unset values write nothing. */
export const decl = (vars: Partial<Record<string, string | number>>) =>
  Object.entries(vars)
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => `  --p-${k}: ${v};`)
    .join("\n");

/**
 * The mode blocks of tokens.css. A brand file uses the same selectors, so its values land on the same
 * elements as Percent's, also in nested `data-theme` sections. Empty bodies write no block.
 */
export function modeBlocks(dark: string, light: string): string[] {
  return [
    ...(dark ? [`:root, [data-theme="dark"], [data-theme="system"] {\n${dark}\n}`] : []),
    ...(light
      ? [`[data-theme="light"] {\n${light}\n}`, `@media (prefers-color-scheme: light) {\n  [data-theme="system"] {\n${light.replace(/^/gm, "  ")}\n  }\n}`]
      : []),
  ];
}

/** The brand file: load it after the design-system CSS. Write it with a script and commit the output. */
export function brandCss(brand: Brand): string {
  const vars = decl(brand.vars ?? {});
  // The dark block also targets :root, so a color set only for dark would win on a light <html>:
  // the light blocks repeat Percent's light value (chart colors: unset, so components use their fallback).
  const light: Partial<Record<BrandColor, string>> = {};
  for (const [k, v] of Object.entries(brand.dark ?? {}) as [BrandColor, string | undefined][])
    if (v !== undefined) light[k] = (color.light as Partial<Record<BrandColor, string>>)[k] ?? "initial";
  for (const [k, v] of Object.entries(brand.light ?? {}) as [BrandColor, string | undefined][]) if (v !== undefined) light[k] = v;
  return [
    "/* Generated by brandCss() from @percentsa/tokens. Do not edit. */",
    ...modeBlocks(decl(brand.dark ?? {}), decl(light)),
    ...(vars ? [`:root {\n${vars}\n}`] : []),
    "",
  ].join("\n\n");
}

const PAIRS: [fg: BrandColor, bg: BrandColor, min: number][] = [
  ...(["fg", "fg-2", "fg-3"] as const).flatMap((fg) => (["bg", "surface", "surface-2"] as const).map((bg) => [fg, bg, 4.5] as [BrandColor, BrandColor, number])),
  ["primary-fg", "primary", 4.5],
  // Selected states (radio dot, tab line, slider) are primary: 3:1 like other UI parts (WCAG 1.4.11).
  ["primary", "bg", 3],
  ["primary", "surface", 3],
  ["danger-fg", "danger", 4.5],
  ...(["success", "danger", "warning"] as const).map((fg) => [fg, "bg", 4.5] as [BrandColor, BrandColor, number]),
  ...([1, 2, 3, 4, 5] as const).map((n) => [`chart-${n}`, "bg", 3] as [BrandColor, BrandColor, number]),
];

/**
 * The color pairs that fail WCAG AA in each mode (empty = the brand passes). Tokens the brand does not
 * set use Percent's values. Checked colors must be #rgb or #rrggbb (contrast() throws otherwise).
 */
export function checkBrand(brand: Brand): { mode: Theme; fg: BrandColor; bg: BrandColor; ratio: number; min: number }[] {
  return THEMES.flatMap((mode) => {
    const value = (t: BrandColor) => brand[mode]?.[t] ?? (color[mode] as Partial<Record<BrandColor, string>>)[t];
    return PAIRS.flatMap(([fg, bg, min]) => {
      const a = value(fg);
      const b = value(bg);
      if (!a || !b) return []; // a chart color the brand does not set
      const ratio = contrast(a, b);
      return ratio < min ? [{ mode, fg, bg, ratio, min }] : [];
    });
  });
}
